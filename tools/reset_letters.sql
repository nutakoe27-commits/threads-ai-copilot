-- ЖЁСТКИЙ СБРОС: стереть ВСЕ письма, включая уже отправленные.
--
-- ОБЫЧНЫЙ ПУТЬ ДРУГОЙ. Чтобы переписать письма после правки промпта,
-- нажмите в панели «Переписать письма заново» (или `run.py --stage rewrite`).
-- Он стирает только неотправленные, убирает старые черновики и сразу пишет
-- новые. Отправленные письма он не трогает — и правильно делает.
--
-- Этот файл нужен только в одном случае: вы хотите потерять и отправленные
-- тоже. Например, база набита пробными прогонами, и её проще обнулить.
--
-- ЧЕМ ЭТО ПЛОХО НА БОЕВОЙ БАЗЕ:
--   * текст отправленного письма — это запись того, что получил человек.
--     Стерев его, вы не поймёте, на что он отвечает;
--   * дожимы сломаются: они обязаны не повторять первое письмо, а сравнивать
--     станет не с чем;
--   * компании, уже показанные в утреннем списке, вернутся туда заново.
--
-- Что НЕ трогается в любом случае: сами компании, вердикты по ICP,
-- классификация по сайту, статусы отправки. Повторный прогон не стоит
-- ни одного запроса к Checko — только к модели.
--
--   sqlite3 data/leads.db < tools/reset_letters.sql

